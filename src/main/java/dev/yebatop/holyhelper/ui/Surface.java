package dev.yebatop.holyhelper.ui;

import dev.yebatop.holyhelper.HolyHelperClient;
import net.minecraft.client.MinecraftClient;
import net.minecraft.client.gui.DrawContext;

/**
 * Выход интерфейса мода из пиксельной сетки клиента.
 * <p>
 * Клиент рисует интерфейс в логических пикселях, и при масштабе 2 каждый такой
 * пиксель — квадрат 2×2 на мониторе. Отсюда всё, что выглядит «пиксельным»:
 * рамка в пиксель выходит жирной, у скругления вдвое меньше ступеней, чем нужно
 * глазу, а значок в пять пикселей — это буквально пять квадратов. Сглаживать
 * внутри этой сетки бесполезно: упираешься в саму сетку.
 * <p>
 * Здесь сетка снимается. Матрица сжимается на {@code 1/плотность}, и всё, что
 * рисуется внутри, считается уже в настоящих пикселях монитора. Рамка становится
 * рамкой в один пиксель экрана, у скругления появляется вчетверо больше ступеней,
 * а под значок наконец есть куда положить полутона.
 * <p>
 * Разметка экранов при этом не меняется вовсе. Она остаётся в логических
 * единицах, а в пиксели переводит каждая кисть у себя внутри — иначе пришлось бы
 * переписать все отступы во всех экранах, и первая же ошибка в умножении
 * разъехалась бы по всему моду.
 * <p>
 * Со скиссором есть тонкость: клиент считает его в своих координатах, и остаётся
 * ли он под матрицей прежним — вопрос, на который гадать не нужно. Ставить его
 * следует до входа сюда, обычными логическими числами.
 */
public final class Surface {

    /** Ниже этого интерфейс мода перестаёт читаться, каким бы ни был масштаб игры. */
    private static final int MIN = 2;

    /** Выше этого дробить незачем: разницу глаз уже не берёт, а работы вчетверо. */
    private static final int MAX = 4;

    private Surface() {
    }

    /** Масштаб самой игры: сколько пикселей монитора в одном её логическом. */
    private static int game() {
        MinecraftClient client = MinecraftClient.getInstance();
        if (client == null || client.getWindow() == null) {
            return 2;
        }
        return Math.max(1, client.getWindow().getScaleFactor());
    }

    /**
     * Сколько пикселей монитора приходится на одну единицу интерфейса мода.
     * <p>
     * Раньше мод рисовал прямо в логических пикселях игры, и при масштабе 1
     * его единица становилась одним пикселем монитора: панель шириной сто
     * тридцать два превращалась в полоску в палец шириной, а подпись кеглем
     * семь — в грязь. Мод шёл за настройкой игры туда, где сам читаться
     * перестаёт.
     * <p>
     * Теперь у него свой масштаб. По умолчанию он не опускается ниже двух —
     * это тот размер, в котором мод и рисовался, — но растёт вслед за игрой,
     * если игрок поставил крупнее. Значение из настроек сильнее: тому, кто
     * хочет больше данных на экране, никто не мешает поставить единицу.
     */
    public static int scale() {
        HolyHelperClient mod = HolyHelperClient.instance();
        int chosen = mod == null ? 0 : mod.config().uiScale;
        if (chosen > 0) {
            return Math.max(1, Math.min(MAX, chosen));
        }
        return Math.max(MIN, Math.min(MAX, game()));
    }

    /** Во сколько раз сжать матрицу экрана, чтобы единица мода стала нужного размера. */
    private static float factor() {
        return scale() / (float) game();
    }

    /**
     * Входит в координаты мода. Дальше всё считается в его единицах, и их размер
     * на мониторе уже не зависит от настройки масштаба в игре.
     */
    public static void open(DrawContext ctx) {
        float factor = factor();
        var matrices = ctx.getMatrices();
        matrices.pushMatrix();
        matrices.scale(factor, factor);
    }

    /** Выходит обратно. */
    public static void close(DrawContext ctx) {
        ctx.getMatrices().popMatrix();
    }

    /** Сколько единиц мода помещается в отрезок экрана заданной длины. */
    public static int units(int screenPixels) {
        return Math.max(0, Math.round(screenPixels / factor()));
    }

    /**
     * Переводит координату мыши в единицы мода.
     * <p>
     * Клиент сообщает положение курсора в своих логических пикселях, а интерфейс
     * мода живёт в собственных. Без перевода попадание по вкладке считалось бы не
     * там, где она нарисована, и промах рос бы вместе с масштабом игры.
     */
    public static int toUnits(double screenCoordinate) {
        return (int) Math.floor(screenCoordinate / factor());
    }

    /**
     * Входит в мелкую сетку внутри единицы мода.
     * <p>
     * Это не то же, что {@link #open}. Тот задаёт размер интерфейса на мониторе и
     * зовётся один раз на экран; этот дробит уже заданную единицу на пиксели и
     * зовётся каждой кистью у себя, чтобы рамка вышла в пиксель, а не в единицу.
     * Матрицы складываются: внутри обоих один шаг — один пиксель монитора.
     */
    public static void enter(DrawContext ctx, int density) {
        var matrices = ctx.getMatrices();
        matrices.pushMatrix();
        matrices.scale(1f / density, 1f / density);
    }

    /** Выходит из мелкой сетки. */
    public static void leave(DrawContext ctx) {
        ctx.getMatrices().popMatrix();
    }

    /**
     * На сколько частей кисти дробят одну единицу мода.
     * <p>
     * Ровно на столько, сколько в ней пикселей монитора: мельче рисовать некуда,
     * крупнее — значит остаться со ступеньками.
     */
    public static int density() {
        return scale();
    }
}
