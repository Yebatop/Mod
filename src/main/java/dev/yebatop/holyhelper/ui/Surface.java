package dev.yebatop.holyhelper.ui;

import net.minecraft.client.MinecraftClient;
import net.minecraft.client.gui.DrawContext;

/**
 * Выход интерфейса мода из пиксельной сетки клиента.
 * <p>
 * Клиент рисует интерфейс в логических пикселях, и при масштабе 2 каждый такой
 * пиксель — квадрат 2×2 на мониторе. Отсюда всё, что выглядит «пиксельным»:
 * рамка в пиксель выходит жирной, у скругления вдвое меньше ступеней, чем нужно
 * глазу, а значок в пять пикселей — это буквально пять квадратов. Сглаживать
 * внутри этой сетки бесполезно: упираешься в саму сетку.
 * <p>
 * Здесь сетка снимается. Матрица сжимается на {@code 1/плотность}, и всё, что
 * рисуется внутри, считается уже в настоящих пикселях монитора. Рамка становится
 * рамкой в один пиксель экрана, у скругления появляется вчетверо больше ступеней,
 * а под значок наконец есть куда положить полутона.
 * <p>
 * Разметка экранов при этом не меняется вовсе. Она остаётся в логических
 * единицах, а в пиксели переводит каждая кисть у себя внутри — иначе пришлось бы
 * переписать все отступы во всех экранах, и первая же ошибка в умножении
 * разъехалась бы по всему моду.
 * <p>
 * Со скиссором есть тонкость: клиент считает его в своих координатах, и остаётся
 * ли он под матрицей прежним — вопрос, на который гадать не нужно. Ставить его
 * следует до входа сюда, обычными логическими числами.
 */
public final class Surface {

    /**
     * Мельче этого дробить незачем.
     * <p>
     * При масштабе 4 логический пиксель и так вчетверо крупнее экранного, и
     * разница между четырьмя и восемью ступенями скругления глазу уже недоступна,
     * а четырёхугольников клиенту приходится вчетверо больше.
     */
    private static final int MAX = 4;

    private Surface() {
    }

    /**
     * Сколько пикселей монитора приходится на логический пиксель — столько же
     * шагов получает кисть на каждую логическую единицу.
     */
    public static int density() {
        MinecraftClient client = MinecraftClient.getInstance();
        if (client == null || client.getWindow() == null) {
            return 1;
        }
        return Math.max(1, Math.min(MAX, client.getWindow().getScaleFactor()));
    }

    /** Входит в мелкую сетку. Всё, что нарисовано дальше, считается в пикселях экрана. */
    public static void enter(DrawContext ctx, int density) {
        var matrices = ctx.getMatrices();
        matrices.pushMatrix();
        matrices.scale(1f / density, 1f / density);
    }

    /** Возвращается в обычные координаты. */
    public static void leave(DrawContext ctx) {
        ctx.getMatrices().popMatrix();
    }
}
